/**
 * Indexes public/images into a manifest the CMS can offer in its media pickers.
 *
 * Images live in the repository rather than a blob store, so there is no
 * database row to select from. Reading the folder at runtime is unreliable on
 * serverless hosts, so the index is built here — at build time, from the same
 * files that get deployed — and imported like any other module.
 *
 * Runs automatically before `dev` and `build`; run it by hand with
 * `npm run media:index` after dropping new files in.
 */
import { readdir, writeFile, stat } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join, relative, extname, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const imagesDir = join(root, 'public', 'images');
const outFile = join(root, 'src', 'content', 'media-manifest.ts');

const IMAGE = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif', '.gif', '.svg']);
const VIDEO = new Set(['.mp4', '.webm', '.mov']);

async function walk(dir) {
  const found = [];
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return found;
  }
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      found.push(...(await walk(full)));
      continue;
    }
    const ext = extname(entry.name).toLowerCase();
    if (!IMAGE.has(ext) && !VIDEO.has(ext)) continue;

    const rel = relative(imagesDir, full).split(/[\\/]/).join('/');
    const { size } = await stat(full);
    found.push({
      url: `/images/${rel}`,
      name: entry.name,
      folder: rel.includes('/') ? rel.slice(0, rel.lastIndexOf('/')) : '',
      kind: VIDEO.has(ext) ? 'video' : 'image',
      bytes: size,
    });
  }
  return found;
}

const files = existsSync(imagesDir) ? await walk(imagesDir) : [];
files.sort((a, b) => a.url.localeCompare(b.url));

const banner = `// Generated by scripts/build-media-manifest.mjs — do not edit by hand.
// Regenerate with: npm run media:index

export interface ManifestEntry {
  url: string;
  name: string;
  folder: string;
  kind: 'image' | 'video';
  bytes: number;
}

export const mediaManifest: ManifestEntry[] = ${JSON.stringify(files, null, 2)};
`;

await writeFile(outFile, banner);
console.log(`media manifest: ${files.length} file${files.length === 1 ? '' : 's'} in public/images`);
